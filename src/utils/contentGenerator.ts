/**
 * Normalizes any text strictly to MADNIKE OS Chief Editor format:
 * - Replaces all forbidden em-dashes ("—" and "–") with standard hyphen "-"
 * - Removes banned infobiz cliches
 */
export function enforceChiefEditorFormatting(text: string): string {
  return cleanIvanOSText(text).replace(/\s*[-]{2,}\s*/g, ' - ');
}

/**
 * Checks whether text complies with the 5 Chief Editor rules of MADNIKE OS.
 */
export function auditEditorialCompliance(text: string): EditorialAuditResult {
  const hasForbiddenDashes = /—|–/.test(text);
  const clicheReport = detectCliches(text);
  const lower = text.toLowerCase();

  const ctaSignals = [
    'напиши',
    'пиши',
    'подпис',
    'установи',
    'закажи',
    'забирай',
    'ссылка',
    'переходи',
    '@menshaev',
    'prodamus',
    'chrome web store',
    'директ',
    'комментар',
  ];
  const hasTargetCta = ctaSignals.some((signal) => lower.includes(signal));

  const issues: string[] = [];
  if (hasForbiddenDashes) {
    issues.push('Обнаружено запрещенное длинное тире (— или –). Нужен только дефис "-".');
  }
  if (clicheReport.count > 0 && !clicheReport.matches.every((m) => m.includes('тире'))) {
    issues.push(`Найдены шаблонные фразы: ${clicheReport.matches.join(', ')}`);
  }
  if (clicheReport.longParagraphsCount > 0) {
    issues.push(`Слишком длинные абзацы (> 3 предложений): ${clicheReport.longParagraphsCount} шт.`);
  }
  if (!hasTargetCta) {
    issues.push('Отсутствует нативный призыв к целевому действию (установка, заказ, подписка).');
  }

  return {
    passed: issues.length === 0,
    hasForbiddenDashes,
    clichesCount: clicheReport.count,
    longParagraphsCount: clicheReport.longParagraphsCount,
    hasTargetCta,
    issues,
  };
}

